class RealDatasetTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.svc = SimilarityIndex(DEFAULT_DATA_PATH)
        cls.csv = pd.read_csv(DEFAULT_DATA_PATH).set_index("event_id")
        cls.sample = cls.csv.sample(n=min(25, len(cls.csv)), random_state=1)

    def test_dataset_is_not_flagged_synthetic(self):
        ref = self.svc.find_similar({"magnitude": 6.0, "depth": 10.0, "latitude": 30.0, "longitude": 77.0})["reference"]
        self.assertFalse(ref["synthetic"], "data/usgs_pager_events.info.json must say synthetic: false")

    def test_five_real_unique_matches_that_exclude_the_event_itself(self):
        for event_id, r in self.sample.iterrows():
            with self.subTest(event=event_id):
                inputs = {"magnitude": float(r.magnitude), "depth": float(r.depth), "latitude": float(r.latitude), "longitude": float(r.longitude)}
                res = self.svc.find_similar(inputs, event_id=event_id)
                ids = [m["eventId"] for m in res["matches"]]
                self.assertEqual(len(ids), SIMILARITY_K)
                self.assertEqual(len(ids), len(set(ids)))
                self.assertNotIn(event_id, ids)
                self.assertTrue(all(i in self.csv.index for i in ids), "every match must be a record in the CSV")
                dists = [m["matchDistance"] for m in res["matches"]]
                self.assertEqual(dists, sorted(dists))

    def test_match_fields_equal_the_csv_row(self):
        event_id, r = next(self.sample.iterrows())
        inputs = {"magnitude": float(r.magnitude), "depth": float(r.depth), "latitude": float(r.latitude), "longitude": float(r.longitude)}
        for m in self.svc.find_similar(inputs, event_id=event_id)["matches"]:
            src = self.csv.loc[m["eventId"]]
            self.assertAlmostEqual(m["magnitude"], float(src.magnitude), places=2)
            self.assertAlmostEqual(m["latitude"], float(src.latitude), places=3)
            self.assertEqual(m["historicalPagerAlert"], str(src.pager_alert).strip().lower())


