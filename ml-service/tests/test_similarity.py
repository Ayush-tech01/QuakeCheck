class ExclusionAndCleaningTests(TempDirCase):
    def rows6(self):
        return [row(f"ev{i}", 5.5 + i * 0.1, 10 + i, 30.0 + i * 0.3, 77.0 + i * 0.3, time=f"2014-0{i + 1}-01T00:00:00Z") for i in range(7)]

    def test_returns_five_matches_for_a_valid_event(self):
        res = query(self.index_from(self.rows6()))
        self.assertEqual(res["returned"], 5)
        self.assertEqual(len(res["matches"]), 5)
        self.assertEqual([m["rank"] for m in res["matches"]], [1, 2, 3, 4, 5])
        dists = [m["matchDistance"] for m in res["matches"]]
        self.assertEqual(dists, sorted(dists))
        self.assertIsNone(res["message"])

    def test_current_event_is_excluded_by_id(self):
        svc = self.index_from(self.rows6())
        exact = dict(mag=5.5, depth=10.0, lat=30.0, lng=77.0)   # the current event's own parameters (== ev0)
        without = [m["eventId"] for m in query(svc, **exact)["matches"]]
        self.assertEqual(without[0], "ev0")  # it IS the nearest record when it is not excluded...
        res = query(svc, eventId="ev0", **exact)
        self.assertNotIn("ev0", [m["eventId"] for m in res["matches"]])
        self.assertEqual(res["excludedCurrentEvent"], 1)

    def test_same_event_under_a_different_id_is_excluded(self):
        # USGS can list one earthquake under two ids: same time (±60 s), practically the same place.
        svc = self.index_from([
            row("us-id", 6.0, 10, 30.00, 77.00, time="2020-03-04T05:06:07Z"),
            row("contributor-id", 6.1, 11, 30.10, 77.10, time="2020-03-04T05:06:30Z"),   # same event, 23 s later, ~15 km
            row("aftershock-next-day", 5.8, 10, 30.1, 77.1, time="2020-03-05T05:06:07Z"),
            row("same-time-far-away", 6.0, 10, 40.0, 100.0, time="2020-03-04T05:06:07Z"),   # same second, other continent
            row("filler", 5.0, 50, 0.0, 0.0),
        ])
        res = query(svc, time="2020-03-04T05:06:07Z")
        ids = [m["eventId"] for m in res["matches"]]
        self.assertNotIn("us-id", ids)
        self.assertNotIn("contributor-id", ids)
        self.assertIn("aftershock-next-day", ids)    # different day: a legitimate historical neighbour
        self.assertIn("same-time-far-away", ids)     # coincidence in time only: kept
        self.assertEqual(res["excludedCurrentEvent"], 2)

    def test_event_that_is_not_in_the_dataset_excludes_nothing(self):
        res = query(self.index_from(self.rows6()), eventId="not-in-dataset", time="2026-10-28T10:00:00Z")
        self.assertEqual(res["excludedCurrentEvent"], 0)
        self.assertEqual(res["returned"], 5)

    def test_duplicates_are_not_returned(self):
        svc = self.index_from([
            row("dup-id", 6.0, 10, 30.0, 77.0), row("dup-id", 6.0, 10, 30.0, 77.0),              # same event_id twice
            row("alias-1", 6.2, 12, 30.5, 77.5), row("alias-2", 6.2, 12, 30.5, 77.5),             # same event, two ids
            row("other", 5.0, 30, 10.0, 10.0),
        ])
        res = query(svc)
        ids = [m["eventId"] for m in res["matches"]]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertEqual(res["returned"], 3)  # dup-id, ONE of alias-1/alias-2, other
        cleaning = res["reference"]["cleaning"]
        self.assertEqual(cleaning["droppedDuplicateEvents"], 1)
        self.assertEqual(cleaning["droppedDuplicateRecords"], 1)

    def test_invalid_records_are_dropped_and_counted(self):
        svc = self.index_from([
            row("good-1", 6.0, 10, 30.0, 77.0),
            row("bad-magnitude", "n/a", 10, 30.0, 77.0),
            row("missing-depth", 6.0, "", 30.0, 77.0),
            row("bad-latitude", 6.0, 10, 95.0, 77.0),
            row("bad-longitude", 6.0, 10, 30.0, 200.0),
            row("unknown-label", 6.0, 10, 30.0, 77.0, alert="purple"),
            row("good-2", 5.0, 20, 31.0, 78.0),
        ])
        res = query(svc)
        self.assertEqual(sorted(m["eventId"] for m in res["matches"]), ["good-1", "good-2"])
        cleaning = res["reference"]["cleaning"]
        self.assertEqual(cleaning["rowsRead"], 7)
        self.assertEqual(cleaning["droppedUnknownLabel"], 1)
        self.assertEqual(cleaning["droppedMissingOrInvalidFeatures"], 4)

    def test_missing_time_and_place_are_reported_as_unknown_not_invented(self):
        svc = self.index_from([
            row("no-time", 6.0, 10, 30.0, 77.0, time="", place=""),
            row("garbage-time", 5.9, 10, 30.1, 77.0, time="not-a-date", place="Somewhere"),
        ])
        by_id = {m["eventId"]: m for m in query(svc)["matches"]}
        self.assertIsNone(by_id["no-time"]["time"])
        self.assertIsNone(by_id["no-time"]["place"])
        self.assertIsNone(by_id["garbage-time"]["time"])
        self.assertEqual(by_id["garbage-time"]["place"], "Somewhere")

    def test_dataset_without_time_and_place_columns_still_works(self):
        cols = ["event_id", "magnitude", "depth", "latitude", "longitude", "pager_alert"]
        svc = self.index_from([row("only-core-columns", 6.0, 10, 30.0, 77.0)], columns=cols)
        match = query(svc)["matches"][0]
        self.assertIsNone(match["time"])
        self.assertIsNone(match["place"])

    def test_matches_are_the_real_dataset_records(self):
        rows = [row(f"rec{i}", 5.0 + i * 0.25, 5 + i * 3, 30 + i, 70 + i, alert=["green", "yellow", "orange", "red"][i % 4],
                    time=f"2012-0{i + 1}-15T10:20:30Z", place=f"Place {i}") for i in range(8)]
        svc = self.index_from(rows)
        stored = {r["event_id"]: r for r in rows}
        for m in query(svc)["matches"]:
            src = stored[m["eventId"]]
            self.assertEqual(m["time"], src["time"])
            self.assertEqual(m["place"], src["place"])
            self.assertAlmostEqual(m["magnitude"], src["magnitude"], places=2)
            self.assertAlmostEqual(m["depth"], src["depth"], places=1)
            self.assertAlmostEqual(m["latitude"], src["latitude"], places=3)
            self.assertAlmostEqual(m["longitude"], src["longitude"], places=3)
            self.assertEqual(m["historicalPagerAlert"], src["pager_alert"])
            self.assertTrue(m["historicalPagerLabel"].endswith("(PAGER)"))

    def test_fewer_than_five_returns_only_what_exists(self):
        svc = self.index_from([row("a", 6.0, 10, 30.0, 77.0), row("b", 5.0, 20, 31.0, 78.0), row("c", 7.0, 5, 10.0, 70.0)])
        res = query(svc)
        self.assertEqual(res["returned"], 3)
        self.assertEqual(len(res["matches"]), 3)
        self.assertIn("Only 3", res["message"])
        self.assertEqual(len({m["eventId"] for m in res["matches"]}), 3)  # nothing repeated to fill the list

    def test_only_the_current_event_in_the_dataset_returns_nothing(self):
        res = query(self.index_from([row("only", 6.0, 10, 30.0, 77.0)]), eventId="only")
        self.assertEqual(res["matches"], [])
        self.assertEqual(res["returned"], 0)
        self.assertIn("No valid historical records", res["message"])


