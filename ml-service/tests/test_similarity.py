COLUMNS = ["event_id", "time", "magnitude", "depth", "latitude", "longitude", "pager_alert", "place"]


def row(event_id, mag, depth, lat, lng, alert="green", time="2015-06-01T00:00:00Z", place="SYNTHETIC place"):
    """One hand-built SYNTHETIC historical record (NOT a real earthquake)."""
    return {
        "event_id": event_id, "time": time, "magnitude": mag, "depth": depth,
        "latitude": lat, "longitude": lng, "pager_alert": alert, "place": place,
    }


def write_csv(path, rows, columns=COLUMNS, info=None):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    if info is not None:
        Path(path).with_suffix(".info.json").write_text(json.dumps(info), encoding="utf-8")
    return Path(path)


def body(mag=6.0, depth=10.0, lat=30.0, lng=77.0, **extra):
    return {"magnitude": mag, "depth": depth, "latitude": lat, "longitude": lng, **extra}


def query(index, **kwargs):
    """Validate like the API does, then search."""
    inputs, event_id, event_time = validate_similarity_request(body(**kwargs))
    return index.find_similar(inputs, event_id=event_id, event_time=event_time)


