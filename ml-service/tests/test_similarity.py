        with self.assertRaises(HistoricalDataNotAvailable) as ctx:
            query(SimilarityIndex(self.tmp / "absent.csv"))
        self.assertEqual(ctx.exception.code, "HISTORICAL_DATA_NOT_AVAILABLE")
