# ── Correctness of the distance and the neighbour search ────────────────────
def scalar_haversine_km(lat1, lon1, lat2, lon2):
    """Textbook haversine, written independently of the vectorised version in similarity.py."""
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi, dlmb = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlmb / 2) ** 2
    return 2 * EARTH_RADIUS_KM * math.asin(math.sqrt(a))


class DistanceAndSearchTests(TempDirCase):
    def test_matches_independent_pure_python_implementation(self):
        # SYNTHETIC fixture. Expected neighbours are computed with plain Python loops (no NumPy),
        # from the documented formula, and must equal what the vectorised service returns.
        frame = make_synthetic_dataset(self.csv, n=400, seed=3)
        sigma_m, sigma_z = float(np.std(frame["magnitude"])), float(np.std(frame["depth"]))
        cur = dict(mag=6.3, depth=25.0, lat=28.6, lng=77.2)

        expected = []
        for _, r in frame.iterrows():
            g = SIMILARITY_WEIGHTS["geographic"] * scalar_haversine_km(cur["lat"], cur["lng"], r.latitude, r.longitude) / GEO_SCALE_KM
            m = SIMILARITY_WEIGHTS["magnitude"] * (r.magnitude - cur["mag"]) / sigma_m
            z = SIMILARITY_WEIGHTS["depth"] * (r.depth - cur["depth"]) / sigma_z
            expected.append((math.sqrt(g * g + m * m + z * z), r.event_id))
        expected.sort()

        got = query(SimilarityIndex(self.csv), mag=cur["mag"], depth=cur["depth"], lat=cur["lat"], lng=cur["lng"])["matches"]
        self.assertEqual([m["eventId"] for m in got], [eid for _, eid in expected[:SIMILARITY_K]])
        for m, (dist, _) in zip(got, expected):
            self.assertAlmostEqual(m["matchDistance"], dist, places=3)

    def test_agrees_with_scikit_learn_nearest_neighbors(self):
        # SYNTHETIC fixture. Builds the full pairwise distance matrix with the service's own metric and
        # lets scikit-learn's NearestNeighbors (brute force, precomputed) pick the neighbours. Confirms the
        # top-k selection and tie ordering, and that the metric is symmetric.
        make_synthetic_dataset(self.csv, n=150, seed=5)
        svc = SimilarityIndex(self.csv)
        idx = svc.ensure_loaded()
        n = len(idx.event_ids)

        def point(i):
            return {"magnitude": idx.magnitude[i], "depth": idx.depth[i], "latitude": idx.latitude[i], "longitude": idx.longitude[i]}

        full = np.vstack([SimilarityIndex._distances(idx, point(i))[3] for i in range(n)])
        self.assertTrue(np.allclose(full, full.T, atol=1e-9), "distance must be symmetric")

        nn = NearestNeighbors(n_neighbors=SIMILARITY_K, metric="precomputed", algorithm="brute").fit(full)
        probe = {"magnitude": 6.6, "depth": 40.0, "latitude": -12.0, "longitude": 150.0}
        dist_to_all = SimilarityIndex._distances(idx, probe)[3].reshape(1, -1)
        sk_dist, sk_idx = nn.kneighbors(dist_to_all)

        result = svc.find_similar(probe)["matches"]
        self.assertEqual([m["eventId"] for m in result], [str(idx.event_ids[i]) for i in sk_idx[0]])
        np.testing.assert_allclose([m["matchDistance"] for m in result], sk_dist[0], atol=1e-3)

    def test_haversine_known_values(self):
        # SYNTHETIC fixture; the distances are geometry, which is what is being checked.
        svc = self.index_from([
            row("one-degree-east", 6.0, 10, 0.0, 1.0),
            row("across-antimeridian", 6.5, 10, 0.0, -179.5),
            row("polar-pair", 7.0, 10, 89.0, 180.0),
            row("filler", 5.0, 30, 40.0, 40.0),
        ])
        east = {m["eventId"]: m for m in query(svc, lat=0.0, lng=0.0)["matches"]}
        self.assertAlmostEqual(east["one-degree-east"]["distanceKm"], 111.2, delta=0.2)   # 1° of arc
        wrap = {m["eventId"]: m for m in query(svc, lat=0.0, lng=179.5)["matches"]}
        self.assertAlmostEqual(wrap["across-antimeridian"]["distanceKm"], 111.2, delta=0.2)  # not 359°
        pole = {m["eventId"]: m for m in query(svc, lat=89.0, lng=0.0)["matches"]}
        self.assertAlmostEqual(pole["polar-pair"]["distanceKm"], 222.4, delta=0.5)         # over the pole

    def test_longitude_wraparound_is_treated_as_close(self):
        # A metric that treated lat/lng as plain numbers would call (0,179.5) 359° from (0,-179.5)
        # and rank it BEHIND (0,-170). Great-circle distance ranks it first.
        svc = self.index_from([
            row("wraps-around", 6.0, 10, 0.0, 179.5),
            row("nine-degrees-away", 6.0, 10, 0.0, -170.0),
            row("filler-a", 5.0, 50, 10.0, 10.0),
        ])
        matches = query(svc, lat=0.0, lng=-179.5)["matches"]
        self.assertEqual(matches[0]["eventId"], "wraps-around")

    def test_magnitude_depth_and_geography_all_contribute(self):
        svc = self.index_from([
            row("close-and-similar", 6.1, 12, 30.2, 77.1),
            row("same-size-but-far", 6.0, 10, 30.0, 107.0),     # ~2,900 km away, identical M and depth
            row("near-but-much-smaller", 4.0, 10, 30.1, 77.0),
            row("near-and-deep", 6.0, 600, 30.1, 77.0),
            row("filler-a", 7.5, 40, -20.0, -70.0),
            row("filler-b", 5.2, 80, 10.0, 120.0),
        ])
        order = [m["eventId"] for m in query(svc)["matches"]]
        self.assertEqual(order[0], "close-and-similar")
        self.assertLess(order.index("close-and-similar"), order.index("same-size-but-far"))
        self.assertLess(order.index("close-and-similar"), order.index("near-but-much-smaller"))
        self.assertLess(order.index("close-and-similar"), order.index("near-and-deep"))

    def test_depth_is_weighted_less_than_magnitude(self):
        # A record exactly one σ away in depth must cost less than one exactly one σ away in magnitude
        # (weights 0.5 vs 1.0), and each must cost exactly weight × 1σ when nothing else differs.
        base = [row(f"bulk-{i}", 5.0 + i * 0.1, 10 + i * 5.0, 30.0, 77.0) for i in range(30)]
        idx = self.index_from(base).ensure_loaded()
        here = {"magnitude": 6.0, "depth": 20.0, "latitude": 30.0, "longitude": 77.0}

        def stand_in(magnitude, depth):   # one hypothetical record at the same epicentre
            lat, lon = np.radians([30.0]), np.radians([77.0])
            return SimpleNamespace(
                lat_rad=lat, lon_rad=lon, cos_lat=np.cos(lat),
                magnitude=np.array([magnitude]), depth=np.array([depth]),
                sigma_magnitude=idx.sigma_magnitude, sigma_depth=idx.sigma_depth,
            )

        d_depth = SimilarityIndex._distances(stand_in(6.0, 20.0 + idx.sigma_depth), here)[3][0]
        d_mag = SimilarityIndex._distances(stand_in(6.0 + idx.sigma_magnitude, 20.0), here)[3][0]
        self.assertAlmostEqual(d_depth, SIMILARITY_WEIGHTS["depth"], places=6)
        self.assertAlmostEqual(d_mag, SIMILARITY_WEIGHTS["magnitude"], places=6)
        self.assertLess(d_depth, d_mag)

    def test_ties_are_deterministic(self):
        rows = [row(f"twin-{c}", 6.0, 10, 30.0, 77.0, time=f"2016-01-0{n}T00:00:00Z") for n, c in enumerate("abc", start=1)]
        rows += [row("filler", 4.5, 90, -30.0, 20.0)]
        svc = self.index_from(rows)
        first = [m["eventId"] for m in query(svc)["matches"]]
        second = [m["eventId"] for m in query(SimilarityIndex(self.csv))["matches"]]
        self.assertEqual(first, second)
        self.assertEqual(first[:3], ["twin-a", "twin-b", "twin-c"])  # oldest first on exact ties


